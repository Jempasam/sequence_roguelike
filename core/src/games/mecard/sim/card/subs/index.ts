/**
 * @packageDocumentation
 * The cards of Dungeon of the Mecard, one file for each. A card takes its numbers as parameters: its file
 * exports its class and the card of the catalog made with them, so another range or distance is one
 * `new` away (`new SweepCard(2)`). A mechanism shared by several cards is an abstract class, each card
 * saying only what differs: {@link BlowCard} for the blows, {@link MoveCard} for the moves. A card with no
 * number is an instance of one of the shapes every card takes ({@link ActionCard}, {@link PrepCard},
 * {@link ModifierCard}). A {@link CompositeCard} holds cards: a {@link FusionCard} plays them one after the
 * other, a {@link MergedCard} at once, a {@link RandomCard} one of them. A {@link RewriteCard} rewrites
 * itself from where it stands: the card on its right, the cards of its unit. A {@link SummonCard} summons
 * bodies, a {@link PotionActionCard} pours the potion plugged into it.
 */

