// Generates core/src/engine/assets/AssetPath.ts from the files under assets/, so a typo in a path is a
// compile error rather than a missing file found while playing.
//   npm run assets               regenerates it
//   npm run assets -- --check    fails when it is not up to date, without writing it

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve, sep } from "node:path"
import { fileURLToPath } from "node:url"

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const ASSETS = join(REPO, "assets")
const OUTPUT = join(REPO, "core", "src", "engine", "assets", "AssetPath.ts")
const CHECK = process.argv.includes("--check")

/** What a directory, or a file name without its extension, is written with. */
const SEGMENT = /^[a-z0-9_-]+$/

/** The extensions shipped with the game. A .psd or an .aseprite left in assets/ must not be. */
const EXTENSIONS = [".png", ".ora", ".wav", ".ogg"]

/** The files that keep an empty folder in git, and are not assets. */
const IGNORED = [".gitkeep"]

const errors: string[] = []
const paths = filesUnder(ASSETS).map(file => relative(ASSETS, file).split(sep).join("/"))
for(const path of paths) errors.push(...problemsOf(path))
if(errors.length > 0) fail(`assets/ holds files the game cannot ship:\n${errors.map(e => `  ${e}`).join("\n")}`)

const generated = sourceOf(paths.sort())
if(CHECK){
    const current = readFileSync(OUTPUT, "utf8")
    if(current !== generated) fail(`${relative(REPO, OUTPUT)} is not up to date. Run npm run assets.`)
    console.log(`${relative(REPO, OUTPUT)} is up to date.`)
} else {
    writeFileSync(OUTPUT, generated)
    console.log(`Wrote ${relative(REPO, OUTPUT)}, ${paths.length} assets.`)
}


//// Files ////

function filesUnder(directory: string): string[] {
    return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
        const path = join(directory, entry.name)
        if(entry.isDirectory()) return filesUnder(path)
        return IGNORED.includes(entry.name) ? [] : [path]
    })
}

/** What forbids shipping a file, by its path under assets/: none when it can be shipped. */
function problemsOf(path: string): string[] {
    const segments = path.split("/")
    const file = segments.pop() ?? ""
    const dot = file.lastIndexOf(".")
    const extension = dot < 0 ? "" : file.slice(dot)
    const problems: string[] = []
    if(!EXTENSIONS.includes(extension)) problems.push(`${path}: not one of ${EXTENSIONS.join(", ")}`)
    // Lowercase only, since Windows ignores case and an HTTP server does not: a wrongly cased path would
    // work in dev and fail online.
    const badSegments = [...segments, file.slice(0, dot < 0 ? undefined : dot)].filter(s => !SEGMENT.test(s))
    for(const segment of badSegments) problems.push(`${path}: "${segment}" is not written ${SEGMENT.source}`)
    return problems
}


//// Output ////

function sourceOf(sorted: readonly string[]): string {
    const header = "// Generated by scripts/indexAssets.ts from assets/. Do not edit: run npm run assets.\n\n"
    const doc = "/** The path of a file shipped with the game, under assets/. */\n"
    const union = sorted.length === 0 ? " never" : sorted.map(path => `\n    | ${JSON.stringify(path)}`).join("")
    return `${header}${doc}export type AssetPath =${union}\n`
}

function fail(message: string): never {
    console.error(message)
    process.exit(1)
}
